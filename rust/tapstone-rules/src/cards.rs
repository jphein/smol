//! Card designs. The engine only ever sees a design index (`u16`); UIDs stay in the registry.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Faction {
    Ember,
    Tide,
    Neutral,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Keyword {
    Ranged,
    Shield1,
    Haste,
    Rush,
    Taunt,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Effect {
    Damage { amount: u8, castle_ok: bool },
    Heal { amount: u8 },
    Destroy { max_toughness: u8 },
    Shift, // move target unit one lane (direction in the tap's aux byte)
    Draw { count: u8 },
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CardKind {
    Unit {
        attack: u8,
        toughness: u8,
        keyword: Option<Keyword>,
    },
    Spell(Effect),
    Castle,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct CardDesign {
    pub id: u16,
    pub name: &'static str,
    pub faction: Faction,
    pub cost: u8,
    pub kind: CardKind,
}

const fn unit(
    id: u16,
    name: &'static str,
    faction: Faction,
    cost: u8,
    attack: u8,
    toughness: u8,
    keyword: Option<Keyword>,
) -> CardDesign {
    CardDesign {
        id,
        name,
        faction,
        cost,
        kind: CardKind::Unit {
            attack,
            toughness,
            keyword,
        },
    }
}
const fn spell(
    id: u16,
    name: &'static str,
    faction: Faction,
    cost: u8,
    effect: Effect,
) -> CardDesign {
    CardDesign {
        id,
        name,
        faction,
        cost,
        kind: CardKind::Spell(effect),
    }
}

const fn castle(id: u16, name: &'static str, faction: Faction) -> CardDesign {
    CardDesign {
        id,
        name,
        faction,
        cost: 0,
        kind: CardKind::Castle,
    }
}

